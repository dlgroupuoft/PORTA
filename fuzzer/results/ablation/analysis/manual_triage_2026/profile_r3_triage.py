def main():
    # Expected counts
    EXPECTED = {
        ("authentik", "oidc_jwt"): 25, ("authentik", "saml"): 15,
        ("casdoor", "oidc"): 47, ("casdoor", "saml"): 32,
        ("dex", "oidc_jwt"): 22, ("dex", "saml"): 30,
        ("keycloak", "oidc"): 10, ("keycloak", "saml"): 41,
        ("logto", "oidc_jwt"): 17, ("logto", "saml"): 21,
        ("vault", "oidc_jwt"): 13,
        ("zitadel", "oidc_jwt"): 17, ("zitadel", "saml"): 27,
    }

    # Sanity check
    counts = defaultdict(int)
    for (p, pr, idx) in TRIAGE:
        counts[(p, pr)] += 1
    for k, v in EXPECTED.items():
        actual = counts.get(k, 0)
        if actual != v:
            print(f"MISMATCH {k}: expected={v} actual={actual}")

    total = len(TRIAGE)
    violations = [v for v in TRIAGE.values() if v["verdict"] == "VIOLATION"]
    unexpecteds = [v for v in TRIAGE.values() if v["verdict"] == "UNEXPECTED"]

    tp_count = sum(1 for v in TRIAGE.values() if v["label"] == "TP")
    fp_count = sum(1 for v in TRIAGE.values() if v["label"] == "FP")

    tp_flaws = set()
    high_tp = 0
    med_tp = 0
    low_tp = 0
    fp_reasons = defaultdict(int)
    for v in TRIAGE.values():
        if v["label"] == "TP":
            tp_flaws.add(v["reason"])
            if v["conf"] == "HIGH":
                high_tp += 1
            elif v["conf"] == "MEDIUM":
                med_tp += 1
            else:
                low_tp += 1
        else:
            fp_reasons[v["reason"]] += 1

    rescued = sum(1 for v in TRIAGE.values() if v["verdict"] == "UNEXPECTED" and v["label"] == "TP")

    print(f"=== {RUN} triage summary ===")
    print(f"Total findings: {total}")
    print(f"VIOLATION: {len(violations)} (TP={sum(1 for v in violations if v['label']=='TP')}, FP={sum(1 for v in violations if v['label']=='FP')})")
    v_fp_reasons = defaultdict(int)
    for v in violations:
        if v["label"] == "FP":
            v_fp_reasons[v["reason"]] += 1
    print(f"  VIOLATION FP reasons: {dict(v_fp_reasons)}")
    print(f"UNEXPECTED: {len(unexpecteds)} (rescued TP={rescued})")
    print(f"TP total: {tp_count}  FP total: {fp_count}")
    print(f"TP by confidence: HIGH={high_tp} MEDIUM={med_tp} LOW={low_tp}")
    print(f"Distinct flaws: {sorted(tp_flaws)} ({len(tp_flaws)}/33)")
    print(f"All FP reason breakdown: {dict(fp_reasons)}")


if __name__ == "__main__":
    main()
